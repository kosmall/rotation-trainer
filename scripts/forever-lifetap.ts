// `npm run forever:lifetap [-- --sessions 60 --search-sessions 30 --seed 1]`
// Compares Life Tap strategies (the user's rule, the first threshold policy, new ones), searches the
// best thresholds with a coordinate descent, validates the winners on fresh seeds and writes
// reports/forever_lifetap_strategies.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import { loadParams } from '../src/forever/data/load';
import { ALL_BUILDS, LT_PRESETS, TUNABLES, duelPolicies, evaluatePolicy, searchPolicy, type PolicyOverrides } from '../src/forever/ltpolicy';

const args = process.argv.slice(2);
const num = (name: string, def: number): number => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? Number(args[i + 1]) : def;
};
const sessions = num('sessions', 60);
const searchSessions = num('search-sessions', 30);
const seed = num('seed', 1);
const LEVELS = [40, 45, 50, 55, 59];
const AFF = ['AFF_WRACK', 'AFF_DRAINTANK'];
const DEMO = ['DEMO_PACT_R1', 'DEMO_PACT_VIDEO', 'DEMO_PACT_R2', 'DEMO_FIRE'];
const f = (x: number, d = 1): string => x.toFixed(d);
const out: string[] = [];
const p = (s = ''): void => void out.push(s);
const base = loadParams();
const show = (o: PolicyOverrides): string => {
  const keys = TUNABLES.map((t) => t.key);
  return keys.map((k) => `${k}=${(o[k] as number | undefined) ?? (base[k] as number)}`).join(', ');
};

p('# Life Tap strategies for WoW Forever leveling (40-59)');
p();
p(`Generated by \`npm run forever:lifetap\`. Gear: average, 1 mob per pull unless stated, levels ${LEVELS.join(', ')}; ${sessions} sessions of ${base.session_pulls} pulls per cell, seed ${seed}. Score = mean kills per hour over builds x levels. **Out-of-combat HP regeneration is assumed to be zero** (formula not found); section 5 tests 0.2% and 0.5% of max HP per second. Data caveats are in \`docs/forever-data-ledger.md\`.`);
p();

// 1. presets
p('## 1. The strategies');
p();
p('| Strategy | Rule |');
p('|---|---|');
for (const [name, pr] of Object.entries(LT_PRESETS)) p(`| ${name} | ${pr.description} |`);
p();
const eo = { builds: ALL_BUILDS, levels: LEVELS, profile: 'average', sessions, seed };
const presetScores = Object.entries(LT_PRESETS).map(([name, pr]) => ({ name, score: evaluatePolicy(pr.params, eo) }));
p('## 2. Results of the presets');
p();
p(`| Strategy | mean kills/h | ${ALL_BUILDS.join(' | ')} | deaths/h | food breaks/h | drink s/kill | Life Tap s/kill | downtime |`);
p(`|---|---:|${ALL_BUILDS.map(() => '---:|').join('')}---:|---:|---:|---:|---:|`);
for (const { name, score: s } of [...presetScores].sort((a, b) => b.score.meanKph - a.score.meanKph))
  p(`| ${name} | ${f(s.meanKph)} | ${ALL_BUILDS.map((b) => f(s.perBuild[b] ?? 0)).join(' | ')} | ${f(s.deathsPerHour, 2)} | ${f(s.breaksPerHour)} | ${f(s.drinkSecPerKill)} | ${f(s.lifeTapSecPerKill)} | ${f(100 * s.downtimeShare, 0)}% |`);
p();

// 3. search
p('## 3. Search for the best thresholds');
p();
p(`Coordinate descent from the user's rule over ${TUNABLES.length} parameters (${TUNABLES.map((t) => t.key).join(', ')}), 2 rounds, ${searchSessions} sessions per cell on a separate seed, a change must gain more than 0.25 kills/h. Candidate values per parameter are in \`src/forever/ltpolicy.ts\`.`);
p();
const groups: [string, readonly string[]][] = [['all builds', ALL_BUILDS], ['affliction (AFF_WRACK, AFF_DRAINTANK)', AFF], ['demonology and fire (DEMO_PACT_R1, VIDEO, R2, DEMO_FIRE)', DEMO]];
const found: Record<string, PolicyOverrides> = {};
for (const [label, builds] of groups) {
  const res = searchPolicy({}, { builds, levels: LEVELS, profile: 'average', sessions: searchSessions, seed: seed + 100 }, 2, 0.25);
  found[label] = res.best;
  p(`### ${label}`);
  p();
  p(`Start (user's rule): ${f(res.start.meanKph)} kills/h, ${f(res.start.deathsPerHour, 2)} deaths/h, ${f(res.start.breaksPerHour)} food breaks/h, ${f(res.start.drinkSecPerKill)} s drinking per kill. Found: ${f(res.score.meanKph)} kills/h, ${f(res.score.deathsPerHour, 2)} deaths/h, ${f(res.score.breaksPerHour)} food breaks/h, ${f(res.score.drinkSecPerKill)} s drinking per kill.`);
  p();
  p(res.steps.length ? res.steps.map((s) => `- round ${s.round}: \`${s.key}\` ${s.from} -> ${s.to} (score ${f(s.meanKph)})`).join('\n') : '- no change beat the user\'s rule by the margin.');
  p();
  p(`Policy: ${show(res.best)}`);
  p();
  console.log('searched', label);
}

// 4. validation on fresh seeds
p('## 4. Validation on fresh seeds');
p();
p(`Each found policy against the user's rule on seeds the search never saw (${Math.max(100, sessions * 2)} paired sessions per cell). Difference = found - user's rule, kills/h, with 95% CI; * = significant.`);
p();
const vSessions = Math.max(100, sessions * 2);
const vSeed = seed + 5000;
for (const [label, builds] of groups) {
  const pol = found[label] as PolicyOverrides;
  p(`### ${label}`);
  p();
  p(`| Build | ${LEVELS.join(' | ')} |`);
  p(`|---|${LEVELS.map(() => '---:|').join('')}`);
  let better = 0;
  let worse = 0;
  let tie = 0;
  for (const b of builds) {
    const cells = LEVELS.map((l) => {
      const d = duelPolicies(pol, {}, b, l, { profile: 'average', sessions: vSessions, seed: vSeed });
      if (d.diff.significant) d.diff.mean > 0 ? better++ : worse++;
      else tie++;
      return `${d.diff.mean >= 0 ? '+' : ''}${f(d.diff.mean)}${d.diff.significant ? ' *' : ''}`;
    });
    p(`| ${b} | ${cells.join(' | ')} |`);
  }
  p();
  p(`Better in ${better}, worse in ${worse}, no significant difference in ${tie} of ${better + worse + tie} cells.`);
  p();
  console.log('validated', label);
}

// 5. HP regeneration and pull size
p('## 5. Sensitivity to the unknown: HP regeneration and pull size');
p();
const compared: [string, PolicyOverrides][] = [['USER', {}], ['OLD_THRESHOLD', LT_PRESETS.OLD_THRESHOLD!.params], ['NO_LIFE_TAP', LT_PRESETS.NO_LIFE_TAP!.params], ['best for all builds', found['all builds'] as PolicyOverrides]];
p('Mean kills per hour (all builds, 5 levels) by out-of-combat HP regeneration (share of max HP per second while walking between mobs):');
p();
p('| Strategy | 0 | 0.2%/s | 0.5%/s |');
p('|---|---:|---:|---:|');
for (const [name, pol] of compared) p(`| ${name} | ${[0, 0.002, 0.005].map((r) => f(evaluatePolicy({ ...pol, hp_regen_pct_per_sec: r }, eo).meanKph)).join(' | ')} |`);
p();
p('By the penalty for dying (seconds lost per death; 90 s is an estimate). The strategies differ in how often the warlock dies, so this matters:');
p();
p('| Strategy | 0 s | 45 s | 90 s | 180 s | deaths/h at 90 s |');
p('|---|---:|---:|---:|---:|---:|');
for (const [name, pol] of compared) {
  const sc = [0, 45, 90, 180].map((d) => evaluatePolicy({ ...pol, death_penalty_sec: d }, eo));
  p(`| ${name} | ${sc.map((x) => f(x.meanKph)).join(' | ')} | ${f((sc[2] as (typeof sc)[number]).deathsPerHour, 2)} |`);
}
p();
p('By mobs per pull:');
p();
p('| Strategy | 1 mob | 2 mobs | 3 mobs |');
p('|---|---:|---:|---:|');
for (const [name, pol] of compared) p(`| ${name} | ${([1, 2, 3] as const).map((m) => f(evaluatePolicy(pol, { ...eo, mobs: m }).meanKph)).join(' | ')} |`);
p();
mkdirSync('reports', { recursive: true });
writeFileSync('reports/forever_lifetap_strategies.md', out.join('\n'));
console.log('written reports/forever_lifetap_strategies.md');
