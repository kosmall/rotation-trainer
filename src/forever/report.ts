// Generates reports/forever_leveling_40plus.md from simulation runs (see scripts/forever-report.ts).

import { VARIANT_IDS, loadOrder, loadVariant, variantFromJson } from './builds';
import { compareBuilds } from './compare';
import { loadParams } from './data/load';
import { duelBuilds, type DuelReport, type Side } from './duel';
import { optimizeBuild, toRuns } from './optimizer';
import { PROFILE_IDS } from './stats';
import { DEFAULT_AXES, renderSensitivity, sensitivity } from './sensitivity';
import { TALENTS, TALENT_BY_ID } from './talents';
import { collectVerify } from './verify';
import type { CellMetrics } from './runner';
import type { Params } from './types';

export interface ReportOptions {
  levels: number[];
  respecLevels: number[];
  sessions: number;
  sensSessions: number;
  sensLevels: number[];
  optSessions: number;
  optToLevel: number;
  seed: number;
  /** Fewer axes and builds, for tests. */
  quick?: boolean;
}

export const DEFAULT_REPORT_OPTIONS: ReportOptions = {
  levels: Array.from({ length: 20 }, (_, i) => 40 + i),
  respecLevels: Array.from({ length: 30 }, (_, i) => 30 + i),
  sessions: 100,
  sensSessions: 40,
  sensLevels: [40, 45, 50, 55, 59],
  optSessions: 30,
  optToLevel: 60,
  seed: 1,
};

const f = (x: number, d = 1): string => x.toFixed(d);

function matrix(rows: readonly CellMetrics[], levels: number[], pick: (m: CellMetrics) => number, d = 1): string {
  const ids = [...new Set(rows.map((r) => r.variant))];
  const head = `| Build | ${levels.join(' | ')} |`;
  const sep = `|---|${levels.map(() => '---:|').join('')}`;
  const body = ids.map((id) => `| ${id} | ${levels.map((l) => { const m = rows.find((r) => r.variant === id && r.level === l); return m ? f(pick(m), d) : '-'; }).join(' | ')} |`);
  return [head, sep, ...body].join('\n');
}

/** Consecutive levels with the same value as "a-b" ranges. */
function ranges(levels: number[], keep: (i: number) => boolean): string {
  const out: string[] = [];
  let start: number | null = null;
  for (let i = 0; i <= levels.length; i++) {
    const on = i < levels.length && keep(i);
    if (on && start === null) start = levels[i] as number;
    if (!on && start !== null) {
      const end = levels[i - 1] as number;
      out.push(start === end ? `${start}` : `${start}-${end}`);
      start = null;
    }
  }
  return out.length ? out.join(', ') : 'none';
}

function winnerText(rep: DuelReport, a: string, b: string): string {
  const lv = rep.results.map((r) => r.level);
  const w = rep.winners;
  return `${a} wins (significant) at levels ${ranges(lv, (i) => w[i] === 'a')}; ${b} wins at ${ranges(lv, (i) => w[i] === 'b')}; no significant difference at ${ranges(lv, (i) => w[i] === 'tie')}.`;
}

export function buildReport(o: ReportOptions = DEFAULT_REPORT_OPTIONS): string {
  const base = loadParams();
  const out: string[] = [];
  const p = (s = ''): void => void out.push(s);
  const quick = o.quick === true;

  p('# WoW Forever: warlock leveling builds 40-59 (simulation report)');
  p();
  p(`Generated by \`npm run forever:report\` (seed ${o.seed}; ${o.sessions} sessions of ${base.session_pulls} pulls per cell; the sensitivity analysis uses ${o.sensSessions} sessions per cell). Same-level normal mobs, ${base.mobs_per_pull} mob per pull unless stated, gear profile **average** unless stated.`);
  p();
  p('> **Read this first.** Wowhead Forever and game data were not reachable while this was written, so many numbers (mob HP and damage, pet damage, spell ranks 3+, Wrack, Malevolence, Improved Shadow Bolt, regen and food/drink rates) are estimates flagged `verify: true`. The ranking of builds is only as good as these assumptions; the sensitivity section shows which of them can change the winner. All values live in `src/forever/data/*.json`.');
  p();

  // ---- 1. comparison tables -------------------------------------------------------------------
  const rowsAvg = compareBuilds({ levels: o.levels, profiles: ['average'], sessions: o.sessions, seed: o.seed });
  p('## 1. Comparison of all builds on every level');
  p();
  p('Build orders are in `src/forever/data/builds.json` (the unified lists: AFF_WRACK, AFF_DRAINTANK, DEMO_PACT_R1 = Bane 2/5 + Shadow Bolt rank 1, DEMO_PACT_VIDEO = Bane 5/5 + rank 1, DEMO_PACT_R2 = Bane 5/5 + rank 2, DEMO_PACT_MAXRANK, DEMO_FIRE). Demonology builds respec at 40 from AFF_WRACK.');
  p();
  for (const [title, pick, d] of [
    ['Kills per hour (higher is better), gear: average', (m: CellMetrics) => m.killsPerHour, 1],
    ['Time to kill one mob, seconds (lower is better)', (m: CellMetrics) => m.ttkMean, 1],
    ['Mana spent per kill', (m: CellMetrics) => m.manaPerKill, 0],
    ['HP lost per kill (damage taken minus healing)', (m: CellMetrics) => m.hpPerKill, 0],
    ['Rest time (Life Tap + drink/eat) per kill, seconds', (m: CellMetrics) => m.restSecPerKill, 1],
    ['Drinking per kill, seconds', (m: CellMetrics) => m.drinkSecPerKill, 1],
    ['Breaks per hour (a break = a stop for Life Tap, drink or food)', (m: CellMetrics) => m.breaksPerHour, 1],
    ['Share of time lost to rest, deaths and pet re-summons (%)', (m: CellMetrics) => 100 * m.downtimeShare, 0],
    ['GCD utilisation (%)', (m: CellMetrics) => 100 * m.gcdUtil, 0],
    ['Cast time wasted below the GCD, seconds per kill', (m: CellMetrics) => m.gcdWasteSecPerKill, 2],
  ] as const) {
    p(`### ${title}`);
    p();
    p(matrix(rowsAvg, o.levels, pick, d));
    p();
  }
  for (const profile of PROFILE_IDS.filter((x) => x !== 'average')) {
    const r = compareBuilds({ levels: o.levels, profiles: [profile], sessions: o.sessions, seed: o.seed });
    p(`### Kills per hour, gear: ${profile}`);
    p();
    p(matrix(r, o.levels, (m) => m.killsPerHour));
    p();
  }
  const best = o.levels.map((l) => rowsAvg.filter((r) => r.level === l).sort((a, b) => b.killsPerHour - a.killsPerHour)[0]?.variant ?? '-');
  p(`Best build per level (average gear): ${o.levels.map((l, i) => `${l}: ${best[i]}`).join(', ')}.`);
  p();

  // ---- 2. respec -----------------------------------------------------------------------------
  p('## 2. Respec to Demonology: from which level does it pay off?');
  p();
  const respecA = duelBuilds('DEMO_PACT_R1', 'AFF_WRACK', { levels: o.respecLevels, profile: 'average', sessions: o.sessions, seed: o.seed });
  p('DEMO_PACT_R1 (respec at that level) against staying on AFF_WRACK. A respec at level L gives the Demonology list up to L (the Pact comes at 40). Positive difference = the respec is faster.');
  p();
  p('| Level | AFF_WRACK kills/h | DEMO_PACT_R1 kills/h | difference (95% CI) | rest s/kill (aff / demo) |');
  p('|---:|---:|---:|---|---|');
  for (const r of respecA.results) p(`| ${r.level} | ${f(r.b.killsPerHour)} | ${f(r.a.killsPerHour)} | ${f(r.diff.killsPerHour.mean)} (${f(r.diff.killsPerHour.ci95[0])}..${f(r.diff.killsPerHour.ci95[1])}) | ${f(r.b.restSecPerKill)} / ${f(r.a.restSecPerKill)} |`);
  p();
  const lv = respecA.results.map((r) => r.level);
  const demoBetter = respecA.winners.map((w: Side) => w === 'a');
  let from: number | null = null;
  for (let i = lv.length - 1; i >= 0; i--) {
    if (demoBetter[i]) from = lv[i] as number;
    else break;
  }
  p(`**Recommendation.** ${winnerText(respecA, 'DEMO_PACT_R1', 'AFF_WRACK')} ${from !== null ? `The respec is worth it from level **${from}** on and stays worth it through ${lv[lv.length - 1]} in this model (the model does not include the respec cost in gold).` : 'The respec never pays off at the tested levels in this model.'} Break-even is not "level": the real decision is the gain in kills per hour times the time you still spend levelling against the respec cost, which this simulator does not price.`);
  p();

  // ---- 3. Bane question ----------------------------------------------------------------------
  p('## 3. Bane 2/5 + Shadow Bolt rank 1 or Bane 5/5 + rank 2?');
  p();
  const bane1 = duelBuilds('DEMO_PACT_R1', 'DEMO_PACT_R2', { levels: o.levels, profile: 'average', sessions: o.sessions, seed: o.seed });
  const bane2 = duelBuilds('DEMO_PACT_R1', 'DEMO_PACT_R2', { levels: o.levels, profile: 'average', sessions: o.sessions, seed: o.seed, params: { bane_per_rank: 0.2 } });
  const vid = duelBuilds('DEMO_PACT_R1', 'DEMO_PACT_VIDEO', { levels: o.levels, profile: 'average', sessions: o.sessions, seed: o.seed });
  p('a = DEMO_PACT_R1 (Bane 2/5, rank 1), b = DEMO_PACT_R2 (Bane 5/5, rank 2). Same talent order up to level 40; afterwards R1 spends points on Corruption, Soul Harvest, Improved Shadow Bolt and Improved Life Tap while R2 puts 5 points into Bane first.');
  p();
  p('| Level | R1 kills/h | R2 kills/h | diff, bane 0.1 s/rank | diff, bane 0.2 s/rank | R1 vs VIDEO (Bane 5/5 + rank 1) |');
  p('|---:|---:|---:|---|---|---|');
  bane1.results.forEach((r, i) => {
    const r2 = bane2.results[i];
    const v = vid.results[i];
    if (r2 && v) p(`| ${r.level} | ${f(r.a.killsPerHour)} | ${f(r.b.killsPerHour)} | ${f(r.diff.killsPerHour.mean)}${r.diff.killsPerHour.significant ? ' *' : ''} | ${f(r2.diff.killsPerHour.mean)}${r2.diff.killsPerHour.significant ? ' *' : ''} | ${f(v.diff.killsPerHour.mean)}${v.diff.killsPerHour.significant ? ' *' : ''} |`);
  });
  p();
  p(`\\* = significant paired difference (a - b). With 0.1 s per rank: ${winnerText(bane1, 'R1 (Bane 2/5 + rank 1)', 'R2 (Bane 5/5 + rank 2)')} With 0.2 s per rank: ${winnerText(bane2, 'R1', 'R2')} Against the video variant (Bane 5/5 + rank 1): ${winnerText(vid, 'R1', 'VIDEO')}`);
  p();
  p('Why: at Bane 2/5 the rank 1 bolt is exactly 1.5 s, the GCD, so no cast time is wasted. At Bane 5/5 it is 1.2 s (0.1 s per rank) or 0.7 s (0.2 s per rank) and every cast still waits for the 1.5 s GCD; the shortening is wasted (see the waste table in section 1). Rank 2 at Bane 5/5 is 1.7 s, so the extra Bane points mostly pay for rank 2 hitting harder.');
  p();

  // ---- 4. extra rotation questions ----------------------------------------------------------
  p('## 4. Rotation questions');
  p();
  p('### Skipping Bane of Agony and Curse of the Elements on quick kills (`skip_agony_if_ttk_below`)');
  p();
  p('AFF_WRACK, average gear, curse of the Elements on, kills per hour by threshold (seconds of estimated time to kill; 0 = never skip):');
  p();
  const thresholds = [0, 8, 12, 16];
  p(`| Level | mobs | ${thresholds.map((t) => `skip < ${t}s`).join(' | ')} |`);
  p(`|---:|---:|${thresholds.map(() => '---:|').join('')}`);
  for (const level of quick ? [50] : [40, 50, 59]) {
    for (const mobs of quick ? [1] as const : [1, 3] as const) {
      const cells = thresholds.map((t) => compareBuilds({ levels: [level], profiles: ['average'], sessions: o.sessions, seed: o.seed, mobs, builds: ['AFF_WRACK'], params: { use_curse_of_elements: true, skip_agony_if_ttk_below: t } })[0] as CellMetrics);
      p(`| ${level} | ${mobs} | ${cells.map((c) => f(c.killsPerHour)).join(' | ')} |`);
    }
  }
  p();
  p('### Pull size (1, 2 or 3 mobs), kills per hour at level 50');
  p();
  p(`| Build | 1 mob | 2 mobs | 3 mobs |`);
  p('|---|---:|---:|---:|');
  const sizes = ([1, 2, 3] as const).map((mobs) => compareBuilds({ levels: [50], profiles: ['average'], sessions: o.sessions, seed: o.seed, mobs }));
  for (const id of VARIANT_IDS) p(`| ${id} | ${sizes.map((r) => f(r.find((x) => x.variant === id)?.killsPerHour ?? 0)).join(' | ')} |`);
  p();

  // ---- 5. optimizer -------------------------------------------------------------------------
  p('## 5. Optimizer: best points after the Demonology core');
  p();
  p('Greedy search: with the first 31 points fixed (the Demonic Pact core), every further point goes to the legal modelled talent with the highest kills per hour at the level it is taken (common random numbers). Order shown from level 41. Compared with the hand-written list at the end.');
  p();
  const templates = quick ? ['DEMO_PACT_R1'] : ['DEMO_PACT_R1', 'DEMO_PACT_R2', 'DEMO_FIRE'];
  for (const id of templates) {
    const v = loadVariant(id);
    const core = loadOrder(v.order).slice(0, 31);
    const res = optimizeBuild({ template: v, core, toLevel: o.optToLevel, profile: 'average', sessions: o.optSessions, seed: o.seed, params: base });
    p(`**${id}**: ${toRuns(res.order.slice(31)).map(([t, n]) => `${TALENT_BY_ID.get(t)?.name ?? t} ${n}`).join(', ')}.`);
    p();
    if (res.order.length === 51) {
      const custom = variantFromJson({ ...v, id: `${id}_OPT`, order: res.order.map((t) => [t, 1]) } as unknown as Record<string, unknown>);
      const cmp = duelBuilds(custom, v, { levels: quick ? [50] : [45, 50, 55, 59], profile: 'average', sessions: o.sessions, seed: o.seed });
      p(`Optimised against the hand-written list (kills/h a=optimised, b=list): ${cmp.results.map((r) => `${r.level}: ${f(r.a.killsPerHour)} vs ${f(r.b.killsPerHour)}`).join('; ')}.`);
      p();
    }
  }

  // ---- 6. sensitivity ------------------------------------------------------------------------
  p('## 6. Sensitivity of the ranking to the unverified assumptions');
  p();
  const sens = sensitivity({ levels: o.sensLevels, profile: 'average', sessions: o.sensSessions, seed: o.seed, axes: quick ? DEFAULT_AXES.slice(0, 1) : undefined });
  p(renderSensitivity(sens));
  p();
  p('Per axis the table shows the best build at each tested level. "Winner changes at" lists the levels where that value gives another winner than the base run. The base ranking at each level is in section 1.');
  p();

  // ---- 7. assumptions -----------------------------------------------------------------------
  const verify = collectVerify();
  p('## 7. All assumptions flagged `verify: true`');
  p();
  p(`${verify.length} entries. Replace them with confirmed values from Wowhead Forever or the game and rerun \`npm run forever:report\`.`);
  p();
  p('| File | Name | Source / note |');
  p('|---|---|---|');
  for (const a of verify) p(`| ${a.file} | ${a.name} | ${a.source.replace(/\|/g, '/')} |`);
  p();
  p('### Talents that are not modelled');
  p();
  p('| Talent | Why |');
  p('|---|---|');
  for (const t of TALENTS.filter((x) => x.status === 'unmodelled')) p(`| ${t.name} | ${t.reason ?? ''} |`);
  p();
  p('## 8. What is not modelled');
  p();
  for (const line of [
    'Pet resurrection costs (shards), Soul Shards in general, Health Funnel, Fear/crowd control and kiting, movement, line of sight and travel time of spells.',
    'Gold cost and time of the respec, vendor trips, bags and repairs; elites, rares, quest mobs with special mechanics.',
    'Threat is simplified to two numbers per mob (player and pet) with the 110%/130% overtake rule; Demonic Brand, Searing Pain and Voidwalker Torment feed it.',
    'Pet HP and mana are refilled before every pull; a dead pet costs `pet_resummon_sec`.',
    'Mob HP is fixed per level (no variance), same level as the player, melee only, one swing every 2 s.',
    'Damage multipliers combine multiplicatively (the game may add some of them).',
    'Haste is off by default (`haste_pct` 0) and does not shorten the GCD unless `haste_shortens_gcd` is on.',
  ]) p(`- ${line}`);
  p();
  return out.join('\n');
}
