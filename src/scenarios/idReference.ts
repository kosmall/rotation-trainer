// The id reference of docs/scenario-format.md (rotation scripts Task 3): every id a scenario can
// name, generated from the data itself (spells and auras of the talent presets, the buff catalog,
// the consumables' and the on-use items' actions), so the doc cannot drift from the code
// (tests/scenarios/docs.test.ts compares the doc's generated section with this output;
// `npm run scenario:ids -- --write` rewrites it). Pure; framework-free.

import { TALENT_PRESETS } from '../data/classes/warlock/talentPresets';
import { ITEM_SLOTS } from '../data/items/db';
import type { ItemDb } from '../data/items/types';
import type { AuraDef, EquippedItem } from '../engine/types';
import { DEFAULT_SETUP, STATIC_SETUP_CATALOG } from '../setup/defaults';
import { DEFAULT_GEAR } from '../setup/gear';
import { deriveGearEffects, hasModelledGearEffect } from '../setup/gearEffects';
import type { SetupConfig } from '../setup/types';
import { applyScenarioSetup } from './format';

/** The markers around the generated section in docs/scenario-format.md. */
export const ID_REFERENCE_START = '<!-- scenario-ids:start (generated by `npm run scenario:ids -- --write`; do not edit by hand) -->';
export const ID_REFERENCE_END = '<!-- scenario-ids:end -->';

const sec = (ms: number) => `${Math.round(ms) / 1000}`;
const cell = (s: string) => s.replace(/\|/g, '\\|');
const row = (cells: readonly string[]) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head: readonly string[], rows: readonly (readonly string[])[]) =>
  [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');

/** Where an aura sits: a self aura changes the player's stats or spells; every other one is on the target. */
const side = (a: AuraDef) => (a.selfStatBonuses || a.selfModifiers || a.selfStatMultipliers ? 'self' : 'target');

/** The applied setup of a talent preset with every gear-independent buff enabled (the author's gear). */
function appliedFor(talents: string, db: ItemDb) {
  const config: SetupConfig = {
    ...(structuredClone(DEFAULT_SETUP) as SetupConfig),
    talents,
    enabledBuffs: STATIC_SETUP_CATALOG.map((b) => b.id),
  };
  return applyScenarioSetup(config, db);
}

/**
 * The generated id reference (Markdown, without the markers): gear slot order, talent presets,
 * spells, auras, setup buff ids, consumable item actions and the on-use items of the database.
 */
export function scenarioIdReference(db: ItemDb): string {
  const out: string[] = [];

  out.push('### Gear slots (`setup.gear` index order)');
  out.push('');
  out.push(table(['index', 'slot', "author's item"], ITEM_SLOTS.map((s, i) => [String(i), s, DEFAULT_GEAR[i] ? `${DEFAULT_GEAR[i]!.id} ${db.items[DEFAULT_GEAR[i]!.id]?.name ?? ''}`.trim() : '(empty)'])));
  out.push('');

  out.push('### Talent presets (`setup.talents`: the preset id or its string)');
  out.push('');
  const builds = TALENT_PRESETS.map((p) => ({ p, applied: appliedFor(p.talents, db) }));
  out.push(
    table(
      ['preset id', 'name', 'talent string', 'talent spells'],
      builds.map(({ p, applied }) => [
        `\`${p.id}\``,
        p.name,
        `\`${p.talents}\``,
        ['shadowburn', 'conflagrate'].filter((id) => applied.script.context.spellIds.includes(id)).join(', ') || '(none)',
      ]),
    ),
  );
  out.push('');

  out.push('### Spells (`cast` rules, `cast.<id>.count`, `cd.<id>.*`, `casting.<id>`, `inflight.<id>`)');
  out.push('');
  const spellIds: string[] = [];
  for (const { applied } of builds) for (const id of applied.script.context.spellIds) if (!spellIds.includes(id)) spellIds.push(id);
  const spellDef = (id: string) => builds.flatMap((b) => b.applied.spec.spells).find((s) => s.id === id)!;
  out.push(
    table(
      ['spell id', 'name', 'base cast (s)', 'cooldown (s)', 'in the talent presets'],
      spellIds.map((id) => {
        const s = spellDef(id);
        const inBuilds = builds.filter((b) => b.applied.script.context.spellIds.includes(id)).map((b) => b.p.id);
        return [`\`${id}\``, s.name, sec(s.castTimeMs), sec(s.cooldownMs), inBuilds.length === builds.length ? 'all' : inBuilds.join(', ')];
      }),
    ),
  );
  out.push('');

  out.push('### Auras (`self.aura.<id>.*`, `target.aura.<id>.*`)');
  out.push('');
  const auras = new Map<string, { a: AuraDef; from: string }>();
  const fromCatalog = new Map(STATIC_SETUP_CATALOG.flatMap((b) => [b.effect.selfAura, b.effect.targetAura].filter((a) => a !== undefined).map((a) => [a!.id, b.id] as const)));
  for (const { applied } of builds) {
    for (const a of applied.spec.auras) {
      if (a.hidden || auras.has(a.id) || a.id.startsWith('item-buff:')) continue;
      auras.set(a.id, { a, from: fromCatalog.has(a.id) ? `setup buff \`${fromCatalog.get(a.id)}\`` : 'the build' });
    }
  }
  out.push(
    table(
      ['aura id', 'name', 'on', 'present when'],
      [...auras.values()].map(({ a, from }) => [`\`${a.id}\``, a.name, side(a), from]),
    ),
  );
  out.push('');
  out.push('On-use item buffs are `item-buff:<buff id>` (self): see the item tables below.');
  out.push('');

  out.push('### Setup buff ids (`setup.enabledBuffs`)');
  out.push('');
  out.push(
    table(
      ['buff id', 'name', 'group', 'notes'],
      STATIC_SETUP_CATALOG.map((b) => [
        `\`${b.id}\``,
        b.name,
        b.group,
        [
          b.exclusiveGroup ? `one of group \`${b.exclusiveGroup}\`` : '',
          b.timed ? `timed: default start ${b.timed.defaultStartSec} s for ${b.timed.durationSec} s (\`setup.timed.${b.id}\`)` : '',
          b.effect.action ? `item action \`${b.id}\` (bound only when enabled)` : '',
        ]
          .filter((x) => x !== '')
          .join('; '),
      ]),
    ),
  );
  out.push('');

  out.push('### Consumable item actions (`use` rules, `use.<id>.count`, `cd.<id>.*`; enable them in `setup.enabledBuffs`)');
  out.push('');
  out.push(
    table(
      ['item id', 'action id', 'name', 'cooldown (s)', 'shared cooldown', 'aura it applies'],
      STATIC_SETUP_CATALOG.filter((b) => b.effect.action !== undefined).map((b) => {
        const a = b.effect.action!;
        return [
          `\`${b.id}\``,
          `\`${a.id}\``,
          b.name,
          sec(a.cooldownMs),
          a.sharedCooldown ? `\`${a.sharedCooldown.group}\` ${sec(a.sharedCooldown.ms)} s` : '-',
          b.effect.selfAura ? `\`${b.effect.selfAura.id}\`` : '(mana)',
        ];
      }),
    ),
  );
  out.push('');

  out.push('### On-use items of the item database (`use item:<item id>` when worn: put the item in `setup.gear`)');
  out.push('');
  const rows: string[][] = [];
  const ids = Object.keys(db.items)
    .map(Number)
    .sort((a, b) => a - b);
  for (const id of ids) {
    const item = db.items[id]!;
    if (!Array.isArray(item.useEffects) || item.useEffects.length === 0 || !hasModelledGearEffect(item)) continue;
    const gear: (EquippedItem | null)[] = ITEM_SLOTS.map(() => null);
    const slot = item.slot === 'trinket' ? 'trinket1' : item.slot === 'finger' ? 'finger1' : item.slot;
    gear[ITEM_SLOTS.indexOf(slot)] = { id };
    for (const b of deriveGearEffects(gear, db)) {
      const a = b.effect.action;
      const aura = b.effect.selfAura;
      const stats = item.useEffects.map((u) => Object.entries(u.stats).map(([k, v]) => `+${Math.round(v)} ${k}`).join(', ')).join('; ');
      rows.push([
        String(id),
        b.name,
        item.slot,
        a ? `\`${b.id}\`` : '(pre-pull, no action)',
        a ? `\`${a.id}\`` : '-',
        aura ? `\`${aura.id}\` ${aura.name}: ${stats} for ${sec(aura.durationMs)} s` : stats,
        a ? sec(a.cooldownMs) : '-',
        a?.sharedCooldown ? `\`${a.sharedCooldown.group}\` ${sec(a.sharedCooldown.ms)} s` : '-',
      ]);
    }
  }
  out.push(table(['item', 'name', 'slot', 'item id (use rules)', 'action id', 'buff aura', 'cooldown (s)', 'shared cooldown'], rows));
  return out.join('\n');
}

/** `doc` with the text between the markers replaced by `section`; null when the markers are missing. */
export function replaceIdReference(doc: string, section: string): string | null {
  const start = doc.indexOf(ID_REFERENCE_START);
  const end = doc.indexOf(ID_REFERENCE_END);
  if (start < 0 || end < start) return null;
  return `${doc.slice(0, start + ID_REFERENCE_START.length)}\n\n${section}\n\n${doc.slice(end)}`;
}

/** The text between the markers (trimmed), or null. */
export function extractIdReference(doc: string): string | null {
  const start = doc.indexOf(ID_REFERENCE_START);
  const end = doc.indexOf(ID_REFERENCE_END);
  if (start < 0 || end < start) return null;
  return doc.slice(start + ID_REFERENCE_START.length, end).trim();
}
