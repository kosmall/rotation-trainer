import { describe, expect, it } from 'vitest';
import authorExport from '../../docs/samples/wowsimsexporter-destruction-warlock.json';
import gearSets from '../fixtures/wowsims-warlock-gear-sets.json';
import {
  enchants as authorEnchants,
  gems as authorGems,
  items as authorItems,
} from '../../src/data/classes/warlock/items';
import { ITEM_SLOTS, LOGICAL_SLOTS, PROFESSION_NAMES, itemsForSlot, loadItemDb, logicalSlot, professionName } from '../../src/data/items/db';
import { itemDbSync } from '../../src/data/items/dbSync';
import dbFileText from '../../src/data/items/db.json?raw';
import type { ItemDb, ItemSlot } from '../../src/data/items/types';
import type { RawStats } from '../../src/engine/types';

// The database is generated by `npm run db:build -- <wowsims tbc-new clone>` (scripts/build-item-db.mjs)
// from wowsims/tbc-new assets/database/db.json; see docs/data-sources.md, Part E.

const db: ItemDb = itemDbSync();
const MODELLED_STATS: readonly (keyof RawStats)[] = [
  'intellect',
  'spirit',
  'spellPower',
  'shadowPower',
  'firePower',
  'critRating',
  'hitRating',
  'hasteRating',
  'mp5',
];

/**
 * Upper bound of `JSON.stringify(db).length`: about 1.5x the generated size (the committed file is
 * 359 521 bytes, the stringified data about the same), so a filter change that bloats it fails here.
 */
const DB_JSON_MAX_CHARS = 540_000;

/**
 * Caps of the committed file itself (bytes, raw and gzip). Before the structured item effects
 * (gear item effects Task 1) it was 359 521 raw / 56 610 gzip, after 362 715 / 57 280 (the spec
 * allows under ~100 KB more raw). The caps leave about 17 KB raw and 4.7 KB gzip of headroom.
 */
const DB_FILE_MAX_BYTES = 380_000;
const DB_FILE_MAX_GZIP_BYTES = 62_000;

/**
 * Differences between the hand-written stage 1 tables (src/data/classes/warlock/items.ts, from the
 * author's export) and the generated database, by `kind:id:field`, with the reason. Empty: the
 * database agrees with every stage 1 value that is compared below.
 */
const STAGE1_DIFFERENCE_ALLOWLIST: Readonly<Record<string, string>> = {};

type Equipped = { id?: number; enchant?: number; gems?: number[] };
const sets = (gearSets as { sets: Record<string, { items: Equipped[] }> }).sets;
const author = (authorExport as { gear: { items: Equipped[] } }).gear.items;
const referenced: Equipped[] = [...Object.values(sets).flatMap((s) => s.items), ...author];

function enchantSlots(e: { slot: ItemSlot; extraSlots?: ItemSlot[] }): ItemSlot[] {
  return [e.slot, ...(e.extraSlots ?? [])];
}

describe('item database (generated from wowsims tbc-new)', () => {
  it('every item has id, name, icon, a logical slot, a phase <= 5, and modelled stats or an effect', () => {
    const items = Object.entries(db.items);
    expect(items.length).toBeGreaterThan(1000);
    for (const [key, item] of items) {
      expect(item.id, `item key ${key}`).toBe(Number(key));
      expect(item.name.length, `item ${key} name`).toBeGreaterThan(0);
      expect(item.icon, `item ${key} icon`).toMatch(/^[a-z0-9_-]+$/);
      expect(LOGICAL_SLOTS, `item ${key} slot`).toContain(item.slot);
      expect(item.phase, `item ${key} phase`).toBeGreaterThanOrEqual(1);
      expect(item.phase, `item ${key} phase`).toBeLessThanOrEqual(5);
      for (const [stat, value] of Object.entries(item.stats)) {
        expect(MODELLED_STATS, `item ${key} stat`).toContain(stat);
        // Negative stats are kept (e.g. Kreeg's Mug: Intellect -10); zero is never stored.
        expect(value, `item ${key} ${stat}`).not.toBe(0);
      }
      const hasStats = Object.keys(item.stats).length > 0;
      // An effect is either unmodelled text or structured (useEffects / procEffects, Part F).
      const flagged = (item.effects?.length ?? 0) + (item.useEffects?.length ?? 0) + (item.procEffects?.length ?? 0) > 0;
      expect(hasStats || flagged, `item ${key} (${item.name}) has no modelled stat and no effect`).toBe(true);
      if (item.twoHand) expect(item.slot, `item ${key} two-hander`).toBe('mainHand');
      if (item.socketBonus) expect(item.sockets?.length, `item ${key} socket bonus without sockets`).toBeGreaterThan(0);
    }
  });

  it('pins Voidheart Crown, Icon of the Silver Crescent and Band of the Eternal Sage by hand', () => {
    // db.json 28963: stats {2: 39 stamina, 3: 36 int, 4: 40 healing, 5: 40 spell damage, 13: 19 crit,
    // 31: 164 armor}, gemSockets [1 meta, 2 red], socketBonus[12] = 4 spell hit, setId 645.
    // Wowhead TBC item=28963: the same (+39 Stam, +36 Int, +40 spell damage, +19 spell crit, meta +
    // red socket, socket bonus +4 spell hit rating).
    expect(db.items[28963]).toEqual({
      id: 28963,
      name: 'Voidheart Crown',
      slot: 'head',
      icon: 'inv_crown_01',
      phase: 1,
      stats: { intellect: 36, spellPower: 40, critRating: 19 },
      sockets: ['meta', 'red'],
      socketBonus: { hitRating: 4 },
      setId: 'voidheart-raiment',
      setName: 'Voidheart Raiment',
    });
    // db.json 29370: stats {4: 43, 5: 43}; on use +155 spell damage (stat 5) for 20 s, 2 min cooldown.
    expect(db.items[29370]).toEqual({
      id: 29370,
      name: 'Icon of the Silver Crescent',
      slot: 'trinket',
      icon: 'inv_weapon_shortblade_23',
      phase: 1,
      stats: { spellPower: 43 },
      unique: true,
      // Structured since gear item effects Task 1 (was the text 'On use: Blessing of the Silver
      // Crescent (+155 spell damage, 20 s, 2 min cooldown)'); see tests/data/item-effects-db.test.ts.
      useEffects: [
        { buffName: 'Blessing of the Silver Crescent', buffId: 35163, stats: { spellPower: 155 }, durationMs: 20000, cooldownMs: 120000, group: { id: 1141, ms: 20000 } },
      ],
    });
    // db.json 29305: stats {2: 28 stamina, 3: 25 int, 4: 34, 5: 34, 13: 24}; proc 10%, +95 spell damage 10 s.
    expect(db.items[29305]).toEqual({
      id: 29305,
      name: 'Band of the Eternal Sage',
      slot: 'finger',
      icon: 'inv_jewelry_ring_55',
      phase: 3,
      stats: { intellect: 25, spellPower: 34, critRating: 24 },
      unique: true,
      // Structured since gear item effects Task 1 (was the text 'Proc: Band of the Eternal Sage
      // (+95 spell damage, 10 s)').
      procEffects: [
        { buffName: 'Band of the Eternal Sage', buffId: 35084, stats: { spellPower: 95 }, durationMs: 10000, chance: 0.1, icdMs: 60000, trigger: 'hit' },
      ],
    });
  });

  it("keeps negative stats: Kreeg's Mug (18425) has Intellect -10", () => {
    // db.json 18425: stats {2: 12 stamina, 3: -10 intellect, 16: 15 spirit}; held in the off hand.
    expect(db.items[18425]).toMatchObject({ slot: 'offHand', stats: { intellect: -10, spirit: 15 } });
  });

  it('faction and required profession are carried from db.json', () => {
    // factionRestriction (proto/ui.proto FactionRestriction): 1 Alliance only, 2 Horde only.
    expect(db.items[29155]).toMatchObject({ name: 'Stormcaller', faction: 'horde' });
    expect(db.items[29153]).toMatchObject({ name: 'Blade of the Archmage', faction: 'alliance' });
    // requiredProfession (proto/common.proto Profession): 3 Enchanting, 7 Jewelcrafting.
    expect(db.gems[33131]).toMatchObject({ name: 'Crimson Sun', requiredProfession: 7 });
    expect(db.enchants[2928]).toMatchObject({ name: 'Enchant Ring - Spellpower', requiredProfession: 3 });
    const items = Object.values(db.items);
    expect(items.filter((i) => i.faction === 'horde')).toHaveLength(1);
    expect(items.filter((i) => i.faction === 'alliance')).toHaveLength(18);
    expect(items.filter((i) => i.requiredProfession !== undefined)).toHaveLength(29);
    expect(Object.values(db.gems).filter((g) => g.requiredProfession !== undefined)).toHaveLength(7);
    expect(Object.values(db.enchants).filter((e) => e.requiredProfession !== undefined)).toHaveLength(4);
    const records = [...items, ...Object.values(db.gems), ...Object.values(db.enchants)];
    for (const r of records) {
      if ('faction' in r) expect(['alliance', 'horde']).toContain(r.faction);
      if (r.requiredProfession !== undefined) expect(r.requiredProfession).toBeGreaterThan(0);
    }
  });

  it("the author's 17 items, their gems and enchants equal the stage 1 tables (or are allowlisted)", () => {
    const diffs: string[] = [];
    const check = (key: string, actual: unknown, expected: unknown) => {
      if (JSON.stringify(actual) === JSON.stringify(expected)) return;
      if (STAGE1_DIFFERENCE_ALLOWLIST[key] === undefined) {
        diffs.push(`${key}: db ${JSON.stringify(actual)} vs stage 1 ${JSON.stringify(expected)}`);
      }
    };
    const sortStats = (s: Partial<RawStats> | undefined) =>
      s === undefined ? undefined : Object.fromEntries(Object.entries(s).sort(([a], [b]) => a.localeCompare(b)));

    expect(Object.keys(authorItems)).toHaveLength(17);
    for (const mine of Object.values(authorItems)) {
      const rec = db.items[mine.id];
      expect(rec, `author item ${mine.id} in the database`).toBeDefined();
      if (!rec) continue;
      check(`item:${mine.id}:name`, rec.name, mine.name);
      check(`item:${mine.id}:slot`, rec.slot, mine.slot);
      check(`item:${mine.id}:stats`, sortStats(rec.stats), sortStats(mine.stats));
      check(`item:${mine.id}:sockets`, rec.sockets, mine.sockets);
      check(`item:${mine.id}:socketBonus`, sortStats(rec.socketBonus), sortStats(mine.socketBonus));
      check(`item:${mine.id}:setId`, rec.setId, mine.setId);
    }
    for (const mine of Object.values(authorGems)) {
      const rec = db.gems[mine.id];
      expect(rec, `author gem ${mine.id} in the database`).toBeDefined();
      if (!rec) continue;
      check(`gem:${mine.id}:name`, rec.name, mine.name);
      check(`gem:${mine.id}:color`, rec.color, mine.color);
      check(`gem:${mine.id}:stats`, sortStats(rec.stats), sortStats(mine.stats));
      check(`gem:${mine.id}:metaRequires`, rec.metaRequires, mine.metaRequires);
    }
    for (const mine of Object.values(authorEnchants)) {
      const rec = db.enchants[mine.id];
      expect(rec, `author enchant ${mine.id} in the database`).toBeDefined();
      if (!rec) continue;
      check(`enchant:${mine.id}:stats`, sortStats(rec.stats), sortStats(mine.stats));
    }
    expect(diffs).toEqual([]);
  });

  it('every item, gem and enchant of the wowsims warlock gear sets and of the author export exists and fits', () => {
    expect(Object.keys(sets).sort()).toEqual(
      ['blank', 'destro_fire_preraid', 'destro_fire_t4', 'preraid', 'swp', 't4', 't5', 't6', 'za'].sort(),
    );
    expect(referenced.length).toBeGreaterThan(17 * 8);
    for (const entry of referenced) {
      if (entry.id === undefined || entry.id === 0) continue;
      const item = db.items[entry.id];
      expect(item, `item ${entry.id}`).toBeDefined();
      if (!item) continue;
      const gemIds = (entry.gems ?? []).filter((g) => g !== 0);
      expect(gemIds.length, `item ${entry.id}: gems beyond its sockets`).toBeLessThanOrEqual(item.sockets?.length ?? 0);
      for (const gemId of gemIds) {
        const gem = db.gems[gemId];
        expect(gem, `gem ${gemId} (item ${entry.id})`).toBeDefined();
        expect(gem?.color, `gem ${gemId} colour`).toMatch(/^(meta|red|blue|yellow|orange|purple|green|prismatic)$/);
        expect(Object.keys(gem?.stats ?? {}).length, `gem ${gemId} modelled stats`).toBeGreaterThan(0);
      }
      if (entry.enchant !== undefined && entry.enchant !== 0) {
        const enchant = db.enchants[entry.enchant];
        expect(enchant, `enchant ${entry.enchant} (item ${entry.id})`).toBeDefined();
        if (enchant) expect(enchantSlots(enchant), `enchant ${entry.enchant} slot`).toContain(item.slot);
      }
    }
  });

  it('every meta gem carries its activation requirement', () => {
    const metas = Object.values(db.gems).filter((g) => g.color === 'meta');
    expect(metas.length).toBeGreaterThanOrEqual(18);
    for (const meta of metas) {
      const hasMin = meta.metaRequires !== undefined && Object.keys(meta.metaRequires).length > 0;
      const hasCompare = meta.metaCompare !== undefined;
      expect(hasMin !== hasCompare, `meta ${meta.id} ${meta.name}: exactly one kind of requirement`).toBe(true);
    }
    // tbc-new sim/core/reforge_optimizer/meta_gem_constraints.go
    expect(db.gems[34220]?.metaRequires).toEqual({ blue: 2 });
    expect(db.gems[25893]?.metaCompare).toEqual({ more: 'blue', than: 'yellow' });
    expect(db.gems[25901]?.metaRequires).toEqual({ red: 2, yellow: 2, blue: 2 });
  });

  it('every gem and enchant has an icon; enchants have a logical slot', () => {
    for (const [key, gem] of Object.entries(db.gems)) {
      expect(gem.id, `gem key ${key}`).toBe(Number(key));
      expect(gem.icon, `gem ${key} icon`).toMatch(/^[a-z0-9_-]+$/);
      expect(gem.phase, `gem ${key} phase`).toBeLessThanOrEqual(5);
    }
    for (const [key, enchant] of Object.entries(db.enchants)) {
      expect(enchant.id, `enchant key ${key}`).toBe(Number(key));
      expect(enchant.icon, `enchant ${key} icon`).toMatch(/^[a-z0-9_-]+$/);
      for (const slot of enchantSlots(enchant)) expect(LOGICAL_SLOTS, `enchant ${key} slot`).toContain(slot);
      // No enchant fits a neck, trinket, held-in-off-hand item or wand (scopes and shield enchants are dropped).
      for (const slot of ['neck', 'trinket', 'offHand', 'ranged'] as const) {
        expect(enchantSlots(enchant), `enchant ${key} (${enchant.name})`).not.toContain(slot);
      }
    }
    // Duplicated effect id in db.json (bracer and boots): one record, both slots.
    expect(enchantSlots(db.enchants[2649]!).sort()).toEqual(['feet', 'wrist']);
  });

  it('only warlock-equippable items: no other-class items, no non-cloth armour, no forbidden weapons', () => {
    const absent: [number, string][] = [
      [20264, 'Peacekeeper Gauntlets: plate'],
      [18373, 'Chestplate of Tranquility: leather'],
      [15047, 'Red Dragonscale Breastplate: mail'],
      [14152, 'Robe of the Archmage: classAllowlist [mage]'],
      [17105, 'Aurastone Hammer: one-hand mace'],
      [21188, 'Fist of Cenarius: two-hand mace'],
      [22336, 'Draconian Aegis of the Legion: shield'],
      [29275, 'Searing Sunblade: off-hand-only dagger (warlocks do not dual wield)'],
      [35332, 'Dreadweave Robe: Horde only (the trainer models a Gnome)'],
      [24583, "Outlander's Tunic: random suffix item"],
    ];
    for (const [id, why] of absent) expect(db.items[id], why).toBeUndefined();

    expect(db.items[34182]).toMatchObject({ slot: 'mainHand', twoHand: true }); // staff
    expect(db.items[17103]).toMatchObject({ slot: 'mainHand' }); // one-hand sword
    expect(db.items[17103]?.twoHand).toBeUndefined();
    expect(db.items[32237]).toMatchObject({ slot: 'mainHand' }); // main-hand dagger
    expect(db.items[28734]).toMatchObject({ slot: 'offHand' }); // held in off-hand
    expect(db.items[29982]).toMatchObject({ slot: 'ranged' }); // wand
    expect(db.items[29153]).toMatchObject({ slot: 'mainHand' }); // Alliance-only sword: kept
    expect(db.items[23207]?.effects?.length).toBeGreaterThan(0); // effect-only trinket kept
  });

  it('ids unique, keys match ids, json size under the limit', async () => {
    const size = JSON.stringify(db).length;
    expect(size).toBeLessThan(DB_JSON_MAX_CHARS);
    const file = new TextEncoder().encode(dbFileText);
    expect(file.length).toBeLessThan(DB_FILE_MAX_BYTES);
    const gzip = await new Response(new Blob([file]).stream().pipeThrough(new CompressionStream('gzip'))).arrayBuffer();
    expect(gzip.byteLength).toBeLessThan(DB_FILE_MAX_GZIP_BYTES);
    for (const table of [db.items, db.gems, db.enchants]) {
      const ids = Object.values(table).map((r) => r.id);
      expect(new Set(ids).size).toBe(ids.length);
    }
  });

  it('ITEM_SLOTS are the 17 WowSimsExporter slots; itemsForSlot offers rings and trinkets in both slots', () => {
    expect(ITEM_SLOTS).toEqual([
      'head', 'neck', 'shoulder', 'back', 'chest', 'wrist', 'hands', 'waist', 'legs', 'feet',
      'finger1', 'finger2', 'trinket1', 'trinket2', 'mainHand', 'offHand', 'ranged',
    ]);
    expect(logicalSlot('finger2')).toBe('finger');
    expect(logicalSlot('trinket1')).toBe('trinket');
    expect(logicalSlot('mainHand')).toBe('mainHand');
    const rings1 = itemsForSlot(db, 'finger1');
    expect(rings1).toEqual(itemsForSlot(db, 'finger2'));
    expect(rings1.map((r) => r.id)).toContain(29305);
    expect(itemsForSlot(db, 'trinket2').map((r) => r.id)).toContain(29370);
    for (const key of ITEM_SLOTS) {
      const list = itemsForSlot(db, key);
      expect(list.length, key).toBeGreaterThan(0);
      for (const item of list) expect(item.slot).toBe(logicalSlot(key));
      // phase, then name
      for (let i = 1; i < list.length; i++) {
        const a = list[i - 1]!;
        const b = list[i]!;
        expect(a.phase < b.phase || (a.phase === b.phase && a.name.localeCompare(b.name) <= 0), `${key} order`).toBe(true);
      }
    }
  });

  it('every item, gem and enchant icon is committed as public/icons/items/<icon>.jpg (npm run icons)', () => {
    const files = new Set(
      Object.keys(import.meta.glob('/public/icons/items/*.jpg')).map((path) =>
        (path.split('/').pop() ?? '').replace(/\.jpg$/, ''),
      ),
    );
    const missing = [db.items, db.gems, db.enchants]
      .flatMap((records) => Object.values(records).map((r) => r.icon))
      .filter((icon) => !files.has(icon));
    expect([...new Set(missing)]).toEqual([]);
  });

  it('PROFESSION_NAMES (one table for the importer and the Gear panel) names every requiredProfession of the database', () => {
    const ids = new Set<number>();
    for (const r of [...Object.values(db.items), ...Object.values(db.gems), ...Object.values(db.enchants)]) {
      if (r.requiredProfession !== undefined) ids.add(r.requiredProfession);
    }
    expect([...ids].sort((a, b) => a - b)).toEqual([1, 3, 4, 7, 11]);
    for (const id of ids) expect(Object.hasOwn(PROFESSION_NAMES, id)).toBe(true);
    expect(professionName(7)).toBe('Jewelcrafting');
    expect(professionName(11)).toBe('Tailoring');
    expect(professionName(99)).toBe('profession 99');
    expect(Object.isFrozen(PROFESSION_NAMES)).toBe(true);
  });

  it('loadItemDb resolves to the same data as itemDbSync', async () => {
    const loaded = await loadItemDb();
    expect(loaded).toEqual(db);
    expect(await loadItemDb()).toBe(loaded);
  });
});
